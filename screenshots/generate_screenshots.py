CHAR_W = 6
CHAR_H = 8
SCALE  = 2   # pixel scale factor → each font pixel becomes 2×2 screen pixels

def _draw_char(pixels, x, y, ch, fg, w, h):
    rows = _FONT_RAW.get(ch, _FONT_RAW[' '])
    for row_i, row_bits in enumerate(rows):
        py = y + row_i * SCALE
        for col_i in range(CHAR_W):
            bit = (row_bits >> (CHAR_W - 1 - col_i)) & 1
            colour = fg if bit else None
            if colour is None:
                continue
            for dy in range(SCALE):
                for dx in range(SCALE):
                    px = x + col_i * SCALE + dx
                    ry = py + dy
                    if 0 <= px < w and 0 <= ry < h:
                        pixels[ry][px] = colour

def _draw_text(pixels, x, y, text, fg, w, h):
    cx = x
    for ch in text:
        _draw_char(pixels, cx, y, ch, fg, w, h)
        cx += CHAR_W * SCALE

def _fill_rect(pixels, x, y, rw, rh, colour, w, h):
    for ry in range(y, min(y + rh, h)):
        for rx in range(x, min(x + rw, w)):
            pixels[ry][rx] = colour

def _png_bytes(pixels, w, h):
    def chunk(tag, data):
        c = struct.pack('>I', len(data)) + tag + data
        return c + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)

    raw = b''
    for row in pixels:
        raw += b'\x00'
        for r, g, b in row:
            raw += bytes([r, g, b])

    ihdr = struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)
    idat = zlib.compress(raw, 9)
    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', ihdr)
            + chunk(b'IDAT', idat)
            + chunk(b'IEND', b''))

