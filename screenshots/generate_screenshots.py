def make_png(spec):
    n_lines = len(spec["lines"])
    img_h = TITLE_H_PX + PAD_Y + n_lines * LINE_H_PX + PAD_Y

    pixels = [[BG] * IMG_W for _ in range(img_h)]

    # title bar
    _fill_rect(pixels, 0, 0, IMG_W, TITLE_H_PX, TITLE, IMG_W, img_h)
    _draw_text(pixels, PAD_X, 8, spec["title"], TITLE_FG, IMG_W, img_h)

    # content lines
    for i, (text, col) in enumerate(spec["lines"]):
        y = TITLE_H_PX + PAD_Y + i * LINE_H_PX
        _draw_text(pixels, PAD_X, y, text, col, IMG_W, img_h)

    out = os.path.join(OUT_DIR, spec["filename"])
    with open(out, "wb") as f:
        f.write(_png_bytes(pixels, IMG_W, img_h))
    print(f"  wrote {spec['filename']}")


